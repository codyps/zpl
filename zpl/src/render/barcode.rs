use crate::output::Path;
// Code 128 symbol widths (alternating bars/spaces), ISO/IEC 15417.
const WIDTHS: [&str; 107] = [
    "212222", "222122", "222221", "121223", "121322", "131222", "122213", "122312", "132212",
    "221213", "221312", "231212", "112232", "122132", "122231", "113222", "123122", "123221",
    "223211", "221132", "221231", "213212", "223112", "312131", "311222", "321122", "321221",
    "312212", "322112", "322211", "212123", "212321", "232121", "111323", "131123", "131321",
    "112313", "132113", "132311", "211313", "231113", "231311", "112133", "112331", "132131",
    "113123", "113321", "133121", "313121", "211331", "231131", "213113", "213311", "213131",
    "311123", "311321", "331121", "312113", "312311", "332111", "314111", "221411", "431111",
    "111224", "111422", "121124", "121421", "141122", "141221", "112214", "112412", "122114",
    "122411", "142112", "142211", "241211", "221114", "413111", "241112", "134111", "111242",
    "121142", "121241", "114212", "124112", "124211", "411212", "421112", "421211", "212141",
    "214121", "412121", "111143", "111341", "131141", "114113", "114311", "411113", "411311",
    "113141", "114131", "311141", "411131", "211412", "211214", "211232", "2331112",
];
pub(super) fn code128(value: &str, module: f64, h: f64) -> Result<Path, String> {
    if !value.bytes().all(|b| (32..=126).contains(&b)) || value.contains('>') {
        return Err("Code 128 supports printable subset B without invocation sequences".into());
    }
    let mut symbols = vec![104usize];
    symbols.extend(value.bytes().map(|b| usize::from(b - 32)));
    let checksum = (104
        + symbols[1..]
            .iter()
            .enumerate()
            .map(|(i, v)| (i + 1) * v)
            .sum::<usize>())
        % 103;
    symbols.extend([checksum, 106]);
    let mut path = Path::default();
    let mut x = 0.;
    for symbol in symbols {
        for (i, w) in WIDTHS[symbol].bytes().enumerate() {
            let width = f64::from(w - b'0') * module;
            if i % 2 == 0 {
                path.rect(x, 0., width, h)
            }
            x += width;
        }
    }
    Ok(path)
}
