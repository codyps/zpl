#!/usr/bin/env python3
"""Generate blittable managed layouts from the authoritative C header.

Default platform alignment and byte flags match zpl-c/include/zpl.h.
https://learn.microsoft.com/en-us/dotnet/standard/native-interop/customize-struct-marshalling
"""
import argparse
from pathlib import Path
import re


def generate(root):
    header = (root / 'zpl-c/include/zpl_config.h').read_text()
    names = {
        'ZplOptionalU32': 'OptionalUInt32', 'ZplOptionalU16': 'OptionalUInt16',
        'ZplOptionalFileId': 'OptionalFileId', 'ZplCompatibility': 'Compatibility',
        'ZplRenderLimits': 'RenderLimits', 'ZplOutputLimits': 'OutputLimits',
        'ZplSyntax': 'Syntax', 'ZplOptions': 'RenderOptions',
    }
    types = dict(names, uint8_t='byte', uint16_t='ushort', uint32_t='uint',
                 uint64_t='ulong', size_t='nuint', double='double')
    text = '// Generated by zpl-dotnet/generate-config.py; do not edit.\n'
    text += 'using System.Runtime.InteropServices;\n\nnamespace Codyps.Zpl;\n'
    for body, name in re.findall(r'typedef struct(?: \w+)? \{([^}]+)\} (\w+);', header):
        text += f'\n[StructLayout(LayoutKind.Sequential)]\npublic partial struct {names[name]}\n{{\n'
        for declaration in body.split(';'):
            if not declaration.strip():
                continue
            match = re.fullmatch(r'\s*(\w+)\s+(\w+)(?:\[(\d+)\])?\s*', declaration)
            if match is None:
                raise ValueError(f'Unsupported C declaration: {declaration}')
            ty, field, count = match.groups()
            field = ''.join(part.capitalize() for part in field.split('_'))
            for index in range(int(count)) if count else [None]:
                text += f'    public {types[ty]} {field}{index if index is not None else ""};\n'
        text += '}\n'
    return text


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    destination = root / 'zpl-dotnet/Codyps.Zpl/Configuration.g.cs'
    content = generate(root)
    if args.check:
        if destination.read_text() != content:
            raise SystemExit('Managed configuration is stale; run zpl-dotnet/generate-config.py')
    else:
        destination.write_text(content)
