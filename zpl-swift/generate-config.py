#!/usr/bin/env python3
"""Generate typed Swift properties from the matching C configuration header.

C layouts remain imported through Clang: Swift never duplicates their ABI layout.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent


def camel(name):
    first, *rest = name.split('_')
    return first + ''.join(word.title() for word in rest)


def generate():
    header = (ROOT.parent / 'zpl-c/include/zpl_config.h').read_text()
    text = '// Generated by generate-config.py; do not edit.\nimport CZpl\n\n'
    for native, name, initializer in [
        ('ZplCompatibility', 'Compatibility', None),
        ('ZplRenderLimits', 'RenderLimits', 'zpl_render_limits_init'),
        ('ZplOutputLimits', 'OutputLimits', 'zpl_output_limits_init'),
        ('ZplSyntax', 'Syntax', 'zpl_syntax_init'),
    ]:
        fields = re.search(r'typedef struct ' + native + r' \{(.*?)\} ' + native + ';', header, re.S)[1]
        text += f'public struct {name} {{\n    internal var raw: {native}\n'
        text += f'    internal init(raw: {native}) {{ self.raw = raw }}\n'
        if initializer:
            text += ('\n    public init() throws {\n        try checkABI()\n'
                     f'        var value = {native}()\n        try check({initializer}(&value))\n'
                     '        raw = value\n    }\n')
        for ctype, field in re.findall(r'^    (\w+) (\w+);$', fields, re.M):
            prop = camel(field)
            read, write = f'raw.{field}', 'newValue'
            if ctype == 'uint8_t' and name == 'Compatibility':
                swift, read, write = 'Bool', f'raw.{field} != 0', 'newValue ? 1 : 0'
            elif ctype in ('ZplOptionalU32', 'ZplOptionalU16'):
                swift = ('UInt32' if ctype == 'ZplOptionalU32' else 'UInt16') + '?'
                read = f'raw.{field}.present == 0 ? nil : raw.{field}.value'
                write = f'{ctype}(present: newValue == nil ? 0 : 1, value: newValue ?? 0)'
            elif ctype == 'ZplOptionalFileId':
                swift = '(UInt16, UInt16, UInt16)?'
                read = f'raw.{field}.present == 0 ? nil : raw.{field}.value'
                write = f'ZplOptionalFileId(present: newValue == nil ? 0 : 1, value: newValue ?? (0, 0, 0))'
            elif ctype == 'size_t':
                swift, read, write = 'UInt', f'UInt(bitPattern: raw.{field})', 'Int(bitPattern: newValue)'
            else:
                swift = {'size_t': 'Int', 'uint32_t': 'UInt32', 'uint64_t': 'UInt64',
                         'uint8_t': 'UInt8', 'double': 'Double'}[ctype]
            text += (f'\n    public var {prop}: {swift} {{\n        get {{ {read} }}\n'
                     f'        set {{ raw.{field} = {write} }}\n    }}\n')
        text += '}\n\n'
    return text.rstrip() + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    destination = ROOT / 'Sources/ZPL/Configuration.swift'
    text = generate()
    if args.check:
        if destination.read_text() != text:
            raise SystemExit('Swift configuration is stale; run zpl-swift/generate-config.py')
    else:
        destination.write_text(text)
